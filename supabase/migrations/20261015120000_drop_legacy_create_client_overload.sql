-- Remove the legacy 5-argument overload of create_client_and_matter.
--
-- Why: the live database carried two overloads of public.create_client_and_matter —
-- the original 5-argument version (20260127045458) and an 11-argument version that
-- adds dob / address / ssn_last4 / phone / email / alternate_addresses. Every
-- optional argument on the 11-argument version has a DEFAULT, so a PostgREST call
-- with the 5 base arguments matched BOTH overloads and failed with
-- "Could not choose the best candidate function" (surfaced in the UI as
-- "RPC call failed"). Add Client was broken for everyone.
--
-- The 11-argument version does everything the 5-argument one did. It was created
-- directly in Lovable Cloud and never recorded in this repo, so this migration also
-- records its canonical definition. The 5-argument overload was dropped on the live
-- database by hand on 2026-10-15; this migration makes that drop reproducible and
-- stops the 20260127045458 migration from ever reintroducing the ambiguity on a
-- rebuilt database.
--
-- Guardrail: do NOT edit this file to make it run. If it errors, the live database
-- differs from what this file assumes, and that difference is the finding.

-- 1. Refuse to run against a database that lacks the 11-argument version. Dropping
--    the 5-argument overload there would leave Add Client with no function at all.
DO $$
DECLARE
  v_count integer;
BEGIN
  SELECT count(*) INTO v_count
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public'
    AND p.proname = 'create_client_and_matter'
    AND p.pronargs = 11;
  IF v_count <> 1 THEN
    RAISE EXCEPTION 'expected exactly one 11-argument public.create_client_and_matter, found %', v_count;
  END IF;
END $$;

-- 2. Drop the legacy overload.
DROP FUNCTION IF EXISTS public.create_client_and_matter(text, public.matter_type, text, text, text);

-- 3. Record the canonical 11-argument definition (identical to live as of 2026-10-15).
CREATE OR REPLACE FUNCTION public.create_client_and_matter(
  _legal_name text,
  _matter_type public.matter_type,
  _intake_raw_text text,
  _intake_source text,
  _client_notes text DEFAULT NULL,
  _dob date DEFAULT NULL,
  _current_address text DEFAULT NULL,
  _ssn_last4 text DEFAULT NULL,
  _phone text DEFAULT NULL,
  _email text DEFAULT NULL,
  _alternate_addresses text[] DEFAULT NULL
)
RETURNS TABLE(client_id uuid, matter_id uuid)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_catalog
AS $$
DECLARE
  v_legal_name text;
  v_client_id uuid;
  v_matter_id uuid;
  v_intake_text text;
  v_intake_source text;
  v_uid uuid := auth.uid();
  v_phone text;
  v_email text;
  v_ssn text;
BEGIN
  v_legal_name := left(nullif(btrim(_legal_name), ''), 100);
  IF v_legal_name IS NULL THEN
    v_legal_name := 'New Client';
  END IF;
  v_intake_text := nullif(btrim(_intake_raw_text), '');
  v_intake_source := left(nullif(btrim(_intake_source), ''), 100);
  IF v_intake_source IS NULL THEN
    v_intake_source := 'Manual';
  END IF;

  -- Normalize phone to digits only
  v_phone := nullif(regexp_replace(coalesce(_phone, ''), '\D', '', 'g'), '');
  v_email := nullif(btrim(lower(coalesce(_email, ''))), '');
  v_ssn := nullif(btrim(coalesce(_ssn_last4, '')), '');
  IF v_ssn IS NOT NULL AND v_ssn !~ '^[0-9]{4}$' THEN
    RAISE EXCEPTION 'ssn_last4 must be exactly 4 digits';
  END IF;

  INSERT INTO public.clients (
    legal_name, owner_id, status, notes,
    date_of_birth, current_address, ssn_last4, phone, email, alternate_addresses
  )
  VALUES (
    v_legal_name, v_uid, 'Active', nullif(btrim(_client_notes), ''),
    _dob,
    nullif(btrim(coalesce(_current_address, '')), ''),
    v_ssn,
    v_phone,
    v_email,
    COALESCE(_alternate_addresses, ARRAY[]::text[])
  )
  RETURNING id INTO v_client_id;

  INSERT INTO public.matters (
    client_id, owner_id, title, matter_type, jurisdiction, primary_state,
    intake_raw_text, intake_source, intake_created_at
  )
  VALUES (
    v_client_id, v_uid,
    v_legal_name || ' - ' || _matter_type::text || ' Matter',
    _matter_type, 'Federal (FCRA)', 'DisputePreparation',
    v_intake_text, v_intake_source,
    CASE WHEN v_intake_text IS NULL THEN NULL ELSE now() END
  )
  RETURNING id INTO v_matter_id;

  RETURN QUERY SELECT v_client_id, v_matter_id;
END;
$$;

REVOKE ALL ON FUNCTION public.create_client_and_matter(
  text, public.matter_type, text, text, text, date, text, text, text, text, text[]
) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.create_client_and_matter(
  text, public.matter_type, text, text, text, date, text, text, text, text, text[]
) TO authenticated, service_role;

-- 4. Prove exactly one overload remains. A second one means a later migration or a
--    hand edit reintroduced the ambiguity.
DO $$
DECLARE
  v_count integer;
BEGIN
  SELECT count(*) INTO v_count
  FROM pg_proc p
  JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname = 'public' AND p.proname = 'create_client_and_matter';
  IF v_count <> 1 THEN
    RAISE EXCEPTION 'expected exactly one public.create_client_and_matter after cleanup, found %', v_count;
  END IF;
END $$;
